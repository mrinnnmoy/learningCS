export function bytesToPhrase(bytes: Buffer): string {
  return Array.from(bytes)
    .map((byte) => WORDLIST[byte])
    .join(" ");
}

export function phraseToBytes(phrase: string): Buffer {
  const words = phrase.trim().split(/\s+/);
  const byteValues = words.map((word) => {
    const index = WORDLIST.indexOf(word);
    if (index === -1) {
      throw new Error(`"${word}" is not in the wordlist — check for typos.`);
    }
    return index;
  });
  return Buffer.from(byteValues);
}
